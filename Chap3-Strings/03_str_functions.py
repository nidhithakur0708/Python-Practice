#1.len

name="Nidhi"
print(len(name)) #length of string

print(name.endswith("hi")) #True (checks if the string ends with "hi")

print(name.startswith("Ni")) #True (checks if the string starts with "Ni")

print(name.upper()) #NIDHI (converts the string to uppercase)

print(name.capitalize()) #Nidhi (capitalizes the first letter of the string)

print(name.find("d")) #3 (finds the index of the first occurrence of "d")

str="Nidhi is a good girl"
print(str.replace("good","bad")) #Nidhi is a bad girl (replaces "good" with "bad")

