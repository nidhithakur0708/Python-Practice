# \n is used to print the next statement in new line
a="Nidhi is a good girl \n She is very good in studies"

# \t is used to print the next statement in tab space
b="Nidhi is a good girl \t She is very good in studies"

 
#Actually printing '' in a statement is not possible because '' is used to define a string. So, to print '' in a statement we use \ before ''.
c='Nidhi is a good girl \n but not a \'bad girl\''
print(c)